"""### Phase 6: Deep Dive Comparative Analysis

In this section, we expand the comparison to include ROC-AUC scores, superimposed ROC curves, and a side-by-side error mapping (Confusion Matrices) for all evaluated models.
"""

from sklearn.metrics import roc_curve, auc, roc_auc_score

updated_metrics = []
plt.figure(figsize=(10, 8))

for name, model in models.items():
    if hasattr(model, "predict_proba"):
        y_probs = model.predict_proba(X_test_proc)[:, 1]
    else:
        y_probs = model.decision_function(X_test_proc)

    fpr, tpr, _ = roc_curve(y_test, y_probs)
    roc_auc = auc(fpr, tpr)

    plt.plot(fpr, tpr, label=f'{name} (AUC = {roc_auc:.2f})')

    y_pred = model.predict(X_test_proc)
    updated_metrics.append({
        "Model": name,
        "Accuracy": accuracy_score(y_test, y_pred),
        "F1-Score": f1_score(y_test, y_pred),
        "ROC-AUC": roc_auc
    })

