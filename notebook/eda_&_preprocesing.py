"""## Phase 2: Refined Data Preprocessing

Following the architectural analysis, we are implementing rigorous preprocessing including One-Hot Encoding, Feature Scaling, and SMOTE for class balance.
"""

from sklearn.preprocessing import StandardScaler, OneHotEncoder
from sklearn.compose import ColumnTransformer
from imblearn.over_sampling import SMOTE
import pandas as pd
import numpy as np

prep_df = df.drop('customerID', axis=1)

X_raw = prep_df.drop('Churn', axis=1)
y_raw = prep_df['Churn'].map({'Yes': 1, 'No': 0})

numeric_features = ['tenure', 'MonthlyCharges', 'TotalCharges']
categorical_features = [col for col in X_raw.columns if col not in numeric_features and col != 'SeniorCitizen']

preprocessor = ColumnTransformer(
    transformers=[
        ('num', StandardScaler(), numeric_features),
        ('cat', OneHotEncoder(drop='first'), categorical_features)
    ],
    remainder='passthrough'
)

X_train_raw, X_test_raw, y_train, y_test = train_test_split(
    X_raw, y_raw, test_size=0.2, random_state=42, stratify=y_raw
)

X_train_proc = preprocessor.fit_transform(X_train_raw)
X_test_proc = preprocessor.transform(X_test_raw)

cat_names = preprocessor.named_transformers_['cat'].get_feature_names_out(categorical_features)
feature_cols = numeric_features + list(cat_names) + ['SeniorCitizen']

print("Preprocessed Feature Shape:", X_train_proc.shape)

smote = SMOTE(random_state=42)
X_train_res, y_train_res = smote.fit_resample(X_train_proc, y_train)

print("Original training shape:", y_train.value_counts().to_dict())
print("Resampled training shape (SMOTE):", pd.Series(y_train_res).value_counts().to_dict())

"""### Evaluation of Refined Preprocessing

With the data balanced and scaled, we can re-train the model to see if recall for churners improves.
"""

rf_refined = RandomForestClassifier(n_estimators=100, random_state=42)
rf_refined.fit(X_train_res, y_train_res)

y_pred_refined = rf_refined.predict(X_test_proc)

print("--- Refined Model Classification Report ---")
print(classification_report(y_test, y_pred_refined))

cm_refined = confusion_matrix(y_test, y_pred_refined)
ConfusionMatrixDisplay(confusion_matrix=cm_refined, display_labels=['No Churn', 'Churn']).plot(cmap='Greens')
plt.title('Confusion Matrix (Refined Preprocessing + SMOTE)')
plt.grid(False)
plt.show()

"""## Phase 5: Machine Learning Models & Comparative Analysis

In this phase, we implement the six required algorithms to establish a comparative framework for churn prediction.
"""

# Duplicate model import block removed
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score

models = {
    "Logistic Regression": LogisticRegression(max_iter=1000, random_state=42),
    "Decision Tree": DecisionTreeClassifier(random_state=42),
    "Random Forest": RandomForestClassifier(n_estimators=100, random_state=42),
    "KNN": KNeighborsClassifier(),
    "SVM": SVC(probability=True, random_state=42),
    "XGBoost": XGBClassifier(eval_metric='logloss', random_state=42)
}

performance_metrics = []
for name, model in models.items():
    model.fit(X_train_res, y_train_res)
    y_pred = model.predict(X_test_proc)
    performance_metrics.append({
        "Model": name,
        "Accuracy": accuracy_score(y_test, y_pred),
        "Precision": precision_score(y_test, y_pred),
        "Recall": recall_score(y_test, y_pred),
        "F1-Score": f1_score(y_test, y_pred)
    })

comparison_df = pd.DataFrame(performance_metrics).sort_values(by='F1-Score', ascending=False)
display(comparison_df)

